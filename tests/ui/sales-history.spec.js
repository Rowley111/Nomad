import { test, expect } from "@playwright/test";
import { emptyState } from "../../src/domain/storage.js";
const KEY = "nomad-workspace-v2";
async function seed(page, legacyOnly = false) {
  const state = emptyState();
  state.inventory = legacyOnly ? [{ id: "legacy", model: "Samsung Galaxy A35 5G", storage: 128, ram: 8, buy: 50000, sell: 89000, status: "Продан", legacy: true, sale: null }] : [{ id: "a35", model: "Samsung Galaxy A35 5G", storage: 128, ram: 8, buy: 50000, sell: 89000, status: "В наличии", date: "2026-09-01", sale: null }];
  await page.addInitScript(({ state, key }) => { if (localStorage.getItem(key) === null) localStorage.setItem(key, JSON.stringify(state)); }, { state, key: KEY });
  await page.goto("/");
}
const workspace = (page) => page.evaluate((key) => JSON.parse(localStorage.getItem(key)), KEY);
test("история помнит фактическую дату, возврат и продажу после удаления карточки", async ({ page }) => {
  await seed(page);
  await page.getByRole("button", { name: "Склад", exact: true }).click();
  await page.getByRole("button", { name: "Зарегистрировать продажу", exact: true }).click();
  await page.getByLabel("Фактическая дата продажи", { exact: true }).fill("2026-10-02");
  await page.getByLabel("Фактическая выручка, ₸", { exact: true }).fill("87000");
  await page.getByLabel("Прямые расходы сделки, ₸ (включая комиссию банка)", { exact: true }).fill("1000");
  await page.getByRole("button", { name: "Подтвердить продажу", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Продажа зарегистрирована");
  await page.getByRole("button", { name: "Продажи", exact: true }).click();
  await expect(page.getByRole("heading", { name: "История продаж (1)", exact: true })).toBeVisible();
  await expect(page.getByLabel("Список проданных телефонов")).toContainText("02.10.2026");
  await page.reload();
  await page.getByRole("button", { name: "Продажи", exact: true }).click();
  await expect(page.getByRole("heading", { name: "История продаж (1)", exact: true })).toBeVisible();
  page.once("dialog", (dialog) => dialog.accept("Клиент вернул устройство"));
  await page.getByRole("button", { name: "Оформить возврат", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Продажа сохранена в истории");
  await expect(page.getByLabel("Список проданных телефонов")).toContainText("Возврат зарегистрирован");
  await page.getByLabel("Продажи с даты", { exact: true }).fill("2026-10-02");
  await page.getByLabel("Продажи по дату", { exact: true }).fill("2026-10-02");
  await expect(page.getByLabel("Продажи по датам")).toContainText(/87\s000/);
  await page.getByLabel("Группировка продаж", { exact: true }).selectOption("week");
  await expect(page.getByLabel("Продажи по датам")).toContainText("Неделя с 28.09.2026");
  await page.getByRole("button", { name: "Склад", exact: true }).click();
  page.once("dialog", (dialog) => dialog.accept());
  await page.getByRole("button", { name: "Удалить", exact: true }).click();
  await expect.poll(async () => (await workspace(page)).inventory.length).toBe(0);
  await page.getByRole("button", { name: "Продажи", exact: true }).click();
  await expect(page.getByRole("heading", { name: "История продаж (1)", exact: true })).toBeVisible();
  await expect(page.getByLabel("Список проданных телефонов")).toContainText("Samsung Galaxy A35 5G");
  await expect(page.getByLabel("Список проданных телефонов")).toContainText("Карточка отсутствует на складе");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
test("старый статус не подменяет сделку: подтверждение требует сумму, дату и основание", async ({ page }) => {
  await seed(page, true);
  await page.getByRole("button", { name: "Продажи", exact: true }).click();
  await expect(page.getByRole("heading", { name: "История продаж (0)", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Проверить старые записи (1)", exact: true }).click();
  await expect(page.getByText("Старый статус — сумма и дата не подтверждены", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Подтвердить старую продажу", exact: true }).click();
  await expect(page.getByLabel("Выручка старой продажи, ₸", { exact: true })).toHaveValue("");
  await expect(page.getByLabel("Фактическая дата старой продажи", { exact: true })).toHaveValue("");
  await page.getByLabel("Выручка старой продажи, ₸", { exact: true }).fill("85000");
  await page.getByLabel("Расходы старой продажи, ₸", { exact: true }).fill("0");
  await page.getByLabel("Способ оплаты старой продажи", { exact: true }).selectOption("Перевод");
  await page.getByLabel("Фактическая дата старой продажи", { exact: true }).fill("2026-10-01");
  await page.getByLabel("Основание подтверждения старой продажи", { exact: true }).fill("Нашли чек перевода");
  await page.getByRole("button", { name: "Сохранить фактическую старую продажу", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Старая продажа подтверждена");
  await expect(page.getByRole("heading", { name: "История продаж (1)", exact: true })).toBeVisible();
  const state = await workspace(page);
  expect(state.inventory[0].sale.revenue).toBe(85000);
  expect(state.inventory[0].sale.at).toBe("2026-10-01");
  expect(state.events.filter((event) => event.type === "sale")).toHaveLength(1);
  expect(state.events.at(-1).historicalConfirmation).toBe(true);
  await page.reload();
  await page.getByRole("button", { name: "Продажи", exact: true }).click();
  await expect(page.getByRole("heading", { name: "История продаж (1)", exact: true })).toBeVisible();
});
